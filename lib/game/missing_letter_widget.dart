            children: List.generate(_word.length, (index) {
              bool isMissing = _missingIndices.contains(index);
              String displayChar = isMissing
                  ? (_missingIndices[0] == index
                  ? (_userEnteredMissing[0].isEmpty ? "_" : _userEnteredMissing[0])
                  : (_userEnteredMissing[1].isEmpty ? "_" : _userEnteredMissing[1]))
                  : _word[index];

              return Container(
                width: 32,
                height: 36,
                margin: const EdgeInsets.symmetric(horizontal: 2.5),
