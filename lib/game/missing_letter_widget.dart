import 'dart:async';
import 'dart:math';
import 'package:flutter/material.dart';

class MissingLetterWidget extends StatefulWidget {
  final VoidCallback onWinBattle;
  final VoidCallback onLoseBattle;

  const MissingLetterWidget({
    super.key,
    required this.onWinBattle,
    required this.onLoseBattle,
  });

  @override
  State<MissingLetterWidget> createState() => _MissingLetterWidgetState();
}

class _MissingLetterWidgetState extends State<MissingLetterWidget> {
  // Master pool of 20 Cybersecurity questions, each containing definition, word, and 2 missing letter indexes
  final List<Map<String, dynamic>> _masterQuestions = [
    {"definition": "A copy of computer data taken and stored elsewhere so that it may be used to restore the original.", "word": "BACKUP", "missingIndices": [1, 4]},
    {"definition": "A network security system that monitors and controls incoming and outgoing network traffic.", "word": "FIREWALL", "missingIndices": [1, 4]},
    {"definition": "The practice of protecting systems, networks, and programs from digital attacks.", "word": "SECURITY", "missingIndices": [1, 3]},
    {"definition": "A software application used to locate, retrieve and display content on the web.", "word": "BROWSER", "missingIndices": [2, 5]},
    {"definition": "A device or program that connects computers to communicate over a network.", "word": "ROUTER", "missingIndices": [1, 3]},
    {"definition": "A private network that connects a group of computers to each other securely.", "word": "INTRANET", "missingIndices": [2, 5]},
    {"definition": "A program designed to replicate itself and spread from one computer to another.", "word": "MALWARE", "missingIndices": [1, 4]},
    {"definition": "An independent piece of malicious code that replicates itself to spread to other files.", "word": "VIRUS", "missingIndices": [1, 3]},
    {"definition": "A type of malware that conceals itself as legitimate software to deceive users.", "word": "TROJAN", "missingIndices": [2, 4]},
    {"definition": "Software designed to block unauthorized access while permitting outward communication.", "word": "DEFENDER", "missingIndices": [2, 5]},
    {"definition": "An encoded representation of data used to secure communications against eavesdroppers.", "word": "CIPHER", "missingIndices": [1, 3]},
    {"definition": "The process of converting plaintext data into unreadable ciphertext.", "word": "ENCRYPT", "missingIndices": [2, 5]},
    {"definition": "A piece of data sent from a website and stored on your computer by your web browser.", "word": "COOKIE", "missingIndices": [2, 4]},
    {"definition": "An unsolicited message sent in bulk over the internet, typically to users for advertising.", "word": "SPAMMER", "missingIndices": [1, 4]},
    {"definition": "A security mechanism for verifying identity before granting system access.", "word": "PASSWORD", "missingIndices": [2, 5]},
    {"definition": "A physical or virtual point where data enters or leaves a network node.", "word": "SOCKET", "missingIndices": [1, 4]},
    {"definition": "A small block of data transmitted across a packet-switched network.", "word": "PACKET", "missingIndices": [2, 4]},
    {"definition": "A unique string of characters used to authenticate a client application or user session.", "word": "TOKENZ", "missingIndices": [1, 4]},
    {"definition": "A fixed-size string generated by a mathematical algorithm to secure data integrity.", "word": "HASHED", "missingIndices": [1, 3]},
    {"definition": "A dedicated high-performance computer that manages network resources and server requests.", "word": "SERVER", "missingIndices": [1, 4]},
  ];

  late List<Map<String, dynamic>> _gameQuestions;
  int _currentIndex = 0;
  late Map<String, dynamic> _currentQ;
  late String _word;
  late List<int> _missingIndices;

  // User input storage for the 2 missing characters in order
  final List<String> _userEnteredMissing = ["", ""];
  int _activeMissingSlot = 0; // 0 or 1

  // 2 Minutes Timer (120 seconds)
  static const int _totalTimeSeconds = 120;
  int _timeLeft = _totalTimeSeconds;
  Timer? _timer;
  bool _gameOver = false;

  @override
  void initState() {
    super.initState();
    // Randomize and select exactly 3 unique questions from the 20 available
    _masterQuestions.shuffle(Random());
    _gameQuestions = _masterQuestions.take(3).toList();

    _loadQuestion();
    _startTimer();
  }

  void _loadQuestion() {
    _currentQ = _gameQuestions[_currentIndex];
    _word = _currentQ["word"]!;
    _missingIndices = List<int>.from(_currentQ["missingIndices"]);
    _userEnteredMissing[0] = "";
    _userEnteredMissing[1] = "";
    _activeMissingSlot = 0;
  }

  void _startTimer() {
    _timer = Timer.periodic(const Duration(seconds: 1), (timer) {
      if (_timeLeft > 0) {
        setState(() {
          _timeLeft--;
        });
      } else {
        _timer?.cancel();
        if (!_gameOver) {
          _gameOver = true;
          widget.onLoseBattle();
        }
      }
    });
  }

  @override
  void dispose() {
    _timer?.cancel();
    super.dispose();
  }

  void _onKeyPress(String letter) {
    if (_gameOver) return;
    setState(() {
      if (_activeMissingSlot < 2) {
        _userEnteredMissing[_activeMissingSlot] = letter;
        if (_activeMissingSlot < 1) {
          _activeMissingSlot++;
        }
      }
    });
  }

  void _onDelete() {
    if (_gameOver) return;
    setState(() {
      if (_activeMissingSlot > 0 && _userEnteredMissing[_activeMissingSlot].isEmpty) {
        _activeMissingSlot--;
        _userEnteredMissing[_activeMissingSlot] = "";
      } else {
        _userEnteredMissing[_activeMissingSlot] = "";
      }
    });
  }

  void _checkAnswer() {
    if (_gameOver) return;

    // Validate if entered letters match the exact missing letters in correct order
    bool isCorrect = true;
    for (int i = 0; i < 2; i++) {
      int charIndex = _missingIndices[i];
      if (_userEnteredMissing[i] != _word[charIndex]) {
        isCorrect = false;
        break;
      }
    }

    if (isCorrect) {
      _advanceToNextOrWin();
    } else {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text("Incorrect missing letters! You must solve this question to proceed.", style: TextStyle(color: Colors.white, decoration: TextDecoration.none)),
          backgroundColor: Color(0xFFD32F2F),
          duration: Duration(milliseconds: 1000),
        ),
      );
    }
  }

  void _advanceToNextOrWin() {
    if (_currentIndex < _gameQuestions.length - 1) {
      setState(() {
        _currentIndex++;
        _loadQuestion();
      });
    } else {
      _timer?.cancel();
      _gameOver = true;
      widget.onWinBattle();
    }
  }

  String _formatTime(int seconds) {
    int minutes = seconds ~/ 60;
    int secs = seconds % 60;
    return "$minutes:${secs.toString().padLeft(2, '0')}";
  }

