import 'dart:math';
import 'package:flutter/foundation.dart';
import 'package:supabase_flutter/supabase_flutter.dart';

class TeacherQuestionItem {
  final String definition;
  final String word;

  TeacherQuestionItem({
    required this.definition,
    required this.word,
  });

  Map<String, dynamic> toJson() => {
        'definition': definition,
        'word': word.trim().toUpperCase(),
      };

  factory TeacherQuestionItem.fromJson(Map<String, dynamic> json) {
    return TeacherQuestionItem(
      definition: json['definition'] as String? ?? 'Cybersecurity concept',
      word: (json['word'] as String? ?? 'SECURITY').trim().toUpperCase(),
    );
  }
}

class TeacherQuizModel {
  final String codeKey;
  final String gameType; // 'missing_letter' or 'caesar_matrix'
  final String difficulty; // 'easy', 'medium', 'hard'
  final List<TeacherQuestionItem> questions;
  final int shift; // Always 3 for Caesar Matrix
  final int missingCount; // Number of missing letters for Missing Letter
  final DateTime createdAt;

  TeacherQuizModel({
    required this.codeKey,
    required this.gameType,
    required this.difficulty,
    required this.questions,
    this.shift = 3,
    this.missingCount = 2,
    DateTime? createdAt,
  }) : createdAt = createdAt ?? DateTime.now();

  Map<String, dynamic> toJson() => {
        'code_key': codeKey,
        'game_type': gameType,
        'difficulty': difficulty,
        'questions': questions.map((q) => q.toJson()).toList(),
        'custom_text': questions.isNotEmpty ? questions.first.word : 'SECURITY',
        'shift': shift,
        'missing_count': missingCount,
        'created_at': createdAt.toIso8601String(),
      };

  factory TeacherQuizModel.fromJson(Map<String, dynamic> json) {
    List<TeacherQuestionItem> qList = [];

    if (json['questions'] != null && json['questions'] is List) {
      qList = (json['questions'] as List)
          .map((item) => TeacherQuestionItem.fromJson(item as Map<String, dynamic>))
          .toList();
    }

    if (qList.isEmpty) {
      final text = json['custom_text'] as String? ?? 'SECURITY';
      qList = [
        TeacherQuestionItem(definition: "Primary concept or word", word: text),
        TeacherQuestionItem(definition: "Network defense mechanism", word: "FIREWALL"),
        TeacherQuestionItem(definition: "Data encryption process", word: "CIPHER"),
      ];
    }

    return TeacherQuizModel(
      codeKey: json['code_key'] as String? ?? '',
      gameType: json['game_type'] as String? ?? 'missing_letter',
      difficulty: json['difficulty'] as String? ?? 'medium',
      questions: qList,
      shift: 3, // Always fixed to +3
      missingCount: (json['missing_count'] as num?)?.toInt() ?? 2,
      createdAt: json['created_at'] != null
          ? DateTime.tryParse(json['created_at'] as String) ?? DateTime.now()
          : DateTime.now(),
    );
  }
}

class TeacherScoreEntry {
  final String codeKey;
  final String username;
  final int score;
  final int timeTakenSeconds;
  final DateTime createdAt;

  TeacherScoreEntry({
    required this.codeKey,
    required this.username,
    required this.score,
    required this.timeTakenSeconds,
    DateTime? createdAt,
  }) : createdAt = createdAt ?? DateTime.now();

  Map<String, dynamic> toJson() => {
        'code_key': codeKey,
        'username': username,
        'score': score,
        'time_taken_seconds': timeTakenSeconds,
        'created_at': createdAt.toIso8601String(),
      };

  factory TeacherScoreEntry.fromJson(Map<String, dynamic> json) {
    return TeacherScoreEntry(
      codeKey: json['code_key'] as String? ?? '',
      username: json['username'] as String? ?? 'Student',
      score: (json['score'] as num?)?.toInt() ?? 0,
      timeTakenSeconds: (json['time_taken_seconds'] as num?)?.toInt() ?? 0,
      createdAt: json['created_at'] != null
          ? DateTime.tryParse(json['created_at'] as String) ?? DateTime.now()
          : DateTime.now(),
    );
  }
}

class TeacherQuizService {
  static final TeacherQuizService _instance = TeacherQuizService._internal();
  factory TeacherQuizService() => _instance;
  TeacherQuizService._internal();

  SupabaseClient? get _client {
    try {
      return Supabase.instance.client;
    } catch (_) {
      return null;
    }
  }

  static final Map<String, TeacherQuizModel> _localQuizzes = {};
  static final Map<String, List<TeacherScoreEntry>> _localScores = {};

  String generateCodeKey() {
    const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    final rnd = Random();
    String code = '';
    for (int i = 0; i < 6; i++) {
      code += chars[rnd.nextInt(chars.length)];
    }
    return code;
  }

  /// Create & Save a new Quiz generated by the Teacher
  Future<String> createQuiz({
    required String gameType,
    required String difficulty,
    required List<TeacherQuestionItem> questions,
    int missingCount = 2,
  }) async {
    final codeKey = generateCodeKey();
    final quiz = TeacherQuizModel(
      codeKey: codeKey,
      gameType: gameType,
      difficulty: difficulty,
      questions: questions,
      shift: 3, // Fixed to +3
      missingCount: missingCount,
    );

    _localQuizzes[codeKey] = quiz;

    final client = _client;
    if (client != null) {
      try {
        await client.from('teacher_quizzes').insert(quiz.toJson());
      } catch (e) {
        debugPrint("Supabase teacher_quizzes insert notice: $e");
      }
    }

    return codeKey;
  }

  /// Fetch Quiz by Code Key
  Future<TeacherQuizModel?> fetchQuiz(String codeKey) async {
    final cleanKey = codeKey.trim().toUpperCase();
    if (cleanKey.isEmpty) return null;

    if (_localQuizzes.containsKey(cleanKey)) {
      return _localQuizzes[cleanKey];
    }

    final client = _client;
    if (client != null) {
      try {
        final res = await client
            .from('teacher_quizzes')
            .select()
            .eq('code_key', cleanKey)
            .maybeSingle();

        if (res != null) {
          final quiz = TeacherQuizModel.fromJson(res);
          _localQuizzes[cleanKey] = quiz;
          return quiz;
        }
      } catch (e) {
        debugPrint("Supabase fetchQuiz notice: $e");
      }
    }

    return null;
  }

  /// Check if a user has already attempted a quiz (1 attempt allowed per account)
  Future<bool> hasUserAttemptedQuiz(String codeKey, String username) async {
    final cleanKey = codeKey.trim().toUpperCase();
    final cleanName = username.trim();
    if (cleanKey.isEmpty || cleanName.isEmpty) return false;

    // Check local scores first
    final localList = _localScores[cleanKey];
    if (localList != null) {
      if (localList.any((e) => e.username.toLowerCase() == cleanName.toLowerCase())) {
        return true;
      }
    }

    final client = _client;
    if (client != null) {
      try {
        final res = await client
            .from('teacher_scores')
            .select('username')
            .eq('code_key', cleanKey)
            .ilike('username', cleanName)
            .maybeSingle();

        if (res != null) {
          return true;
        }
      } catch (e) {
        debugPrint("Supabase hasUserAttemptedQuiz notice: $e");
      }
    }

    return false;
  }

  /// Submit Student Score for a specific Quiz Code Key
  Future<void> submitScore({
    required String codeKey,
    required String username,
    required int score,
    required int timeTakenSeconds,
  }) async {
    final cleanKey = codeKey.trim().toUpperCase();
    final entry = TeacherScoreEntry(
      codeKey: cleanKey,
      username: username.isNotEmpty ? username : "Student",
      score: score,
      timeTakenSeconds: timeTakenSeconds,
    );

    _localScores.putIfAbsent(cleanKey, () => []);
    
    // Prevent duplicate entries in local cache
    _localScores[cleanKey]!.removeWhere(
        (e) => e.username.toLowerCase() == entry.username.toLowerCase());
    _localScores[cleanKey]!.add(entry);
    _localScores[cleanKey]!.sort((a, b) => b.score.compareTo(a.score));

    final client = _client;
    if (client != null) {
      try {
        await client.from('teacher_scores').insert(entry.toJson());
      } catch (e) {
        debugPrint("Supabase teacher_scores insert notice: $e");
      }
    }
  }

  /// Fetch Leaderboard / Scores for a specific Quiz Code Key
  Future<List<TeacherScoreEntry>> fetchScores(String codeKey) async {
    final cleanKey = codeKey.trim().toUpperCase();
    if (cleanKey.isEmpty) return [];

    final client = _client;
    if (client != null) {
      try {
        final res = await client
            .from('teacher_scores')
            .select()
            .eq('code_key', cleanKey)
            .order('score', ascending: false);

        if (res is List && res.isNotEmpty) {
          final list = res.map((item) => TeacherScoreEntry.fromJson(item)).toList();
          _localScores[cleanKey] = list;
          return list;
        }
      } catch (e) {
        debugPrint("Supabase fetchScores notice: $e");
      }
    }

    return _localScores[cleanKey] ?? [];
  }
}
